/**
 * @file `npm run filemap` — regenerate docs/FILEMAP.md from the `@file` header
 * comment at the top of every file in src/. Agents read FILEMAP.md instead of
 * opening files to find what they need.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = 'src'
const skip = new Set(['routeTree.gen.ts'])
const out: string[] = ['# File map', '', '> Generated by `npm run filemap` from each file\'s `@file` header. Do not edit by hand.', '']
const missing: string[] = []

function walk(dir: string) {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(ts|tsx)$/.test(name) && !skip.has(name)) describe(p)
  }
}

function describe(p: string) {
  const src = readFileSync(p, 'utf8')
  const m = src.match(/^\/\*\*([\s\S]*?)\*\//)
  const rel = relative('.', p)
  if (!m || !m[1].includes('@file')) {
    missing.push(rel)
    out.push(`- \`${rel}\` — _(no descriptor)_`)
    return
  }
  const body = m[1]
    .split('\n')
    .map((l) => l.replace(/^\s*\*\s?/, '').trimEnd())
    .join('\n')
    .trim()
    .replace(/^@file\s*/, '')
  const [first, ...rest] = body.split(/\n(?=@)/)
  out.push(`- \`${rel}\` — ${first.replace(/\s*\n\s*/g, ' ')}`)
  for (const tag of rest) out.push(`  - ${tag.replace(/\s*\n\s*/g, ' ')}`)
}

walk(root)
mkdirSync('docs', { recursive: true })
writeFileSync('docs/FILEMAP.md', out.join('\n') + '\n')
console.log(`docs/FILEMAP.md written.${missing.length ? ` Missing descriptors: ${missing.join(', ')}` : ''}`)
